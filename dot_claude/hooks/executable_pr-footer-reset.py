#!/usr/bin/env python3
"""Have Claude rewrite a PR body right after creating it through the GitHub MCP server.

In Claude Code cloud sessions the server appends a `Generated by Claude Code` footer
with the session link on create, ignoring `attribution`; an update keeps the body as
given. A failure never blocks the session.
"""

from __future__ import annotations

import json
import sys


def main() -> int:
    try:
        event = json.load(sys.stdin)
        if not (event.get("tool_name") or "").endswith("create_pull_request"):
            return 0
        body = (event.get("tool_input") or {}).get("body")
        if not isinstance(body, str):
            return 0
        reason = (
            "作成したPRの本文に、GitHub側でClaude Codeの署名とセッションのリンクが追記された。"
            "`mcp__github__update_pull_request` で、本文を次の内容に上書きする。\n\n"
            + body
        )
        print(json.dumps({"decision": "block", "reason": reason}, ensure_ascii=False))
    except Exception:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
